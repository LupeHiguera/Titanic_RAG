"""Retrieval-quality evaluation for the Titanic RAG system.

Computes Hit Rate@5, Recall@5, Recall@10, and MRR against a hand-curated
gold set (Evals/gold_set.json). Also runs a similarity-threshold sweep
to back the system's 0.5 default.

Output is a markdown report written to Evals/EVAL_RESULTS.md plus a
summary printed to stdout.

Usage:
    python Evals/run_retrieval_eval.py            # full eval, default threshold sweep
    python Evals/run_retrieval_eval.py --quick    # skip the threshold sweep
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Set

from dotenv import load_dotenv

load_dotenv()

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from Services.embeddings import EmbeddingService
from Services.vector_storage import PineconeVectorStore
from Services.semantic_search import SemanticSearchEngine, SearchQuery


GOLD_PATH = ROOT / "Evals" / "gold_set.json"
OUT_PATH = ROOT / "Evals" / "EVAL_RESULTS.md"


def load_gold_set() -> List[Dict]:
    with open(GOLD_PATH, encoding="utf-8") as f:
        data = json.load(f)
    return data["queries"]


def witnesses_in_results(results) -> List[str]:
    """Ordered list of witness names from a result list, deduped preserving rank."""
    seen = []
    for r in results:
        name = r.chunk.chunk.witness_name
        if name not in seen:
            seen.append(name)
    return seen


def reciprocal_rank(ranked_witnesses: List[str], relevant: Set[str]) -> float:
    for i, w in enumerate(ranked_witnesses, start=1):
        if w in relevant:
            return 1.0 / i
    return 0.0


def evaluate(engine: SemanticSearchEngine, gold: List[Dict], threshold: float,
             top_k: int = 10) -> Dict:
    """Run the gold set at one threshold; return aggregate + per-query stats."""
    per_query = []
    hits_at_5 = 0
    recall_at_5_vals = []
    recall_at_10_vals = []
    mrr_vals = []
    latencies = []

    for entry in gold:
        relevant = set(entry["relevant_witnesses"])
        t0 = time.perf_counter()
        results = engine.search(SearchQuery(
            text=entry["query"],
            top_k=top_k,
            similarity_threshold=threshold,
        ))
        latencies.append(time.perf_counter() - t0)

        ranked_witnesses = witnesses_in_results(results)
        ranked_at_5 = ranked_witnesses[:5]

        hit5 = bool(set(ranked_at_5) & relevant)
        if hit5:
            hits_at_5 += 1

        recall5 = len(set(ranked_at_5) & relevant) / max(1, len(relevant))
        recall10 = len(set(ranked_witnesses[:10]) & relevant) / max(1, len(relevant))
        mrr = reciprocal_rank(ranked_witnesses, relevant)

        recall_at_5_vals.append(recall5)
        recall_at_10_vals.append(recall10)
        mrr_vals.append(mrr)

        per_query.append({
            "query": entry["query"],
            "topic": entry["topic"],
            "relevant": sorted(relevant),
            "retrieved_top5": ranked_at_5,
            "retrieved_top10": ranked_witnesses[:10],
            "hit@5": hit5,
            "recall@5": recall5,
            "recall@10": recall10,
            "mrr": mrr,
            "raw_results_count": len(results),
        })

    n = len(gold)
    return {
        "threshold": threshold,
        "n_queries": n,
        "hit_rate_at_5": hits_at_5 / n,
        "recall_at_5_mean": statistics.mean(recall_at_5_vals),
        "recall_at_10_mean": statistics.mean(recall_at_10_vals),
        "mrr": statistics.mean(mrr_vals),
        "p50_latency_ms": statistics.median(latencies) * 1000,
        "p95_latency_ms": sorted(latencies)[int(0.95 * n)] * 1000 if n > 1 else latencies[0] * 1000,
        "per_query": per_query,
    }


def render_md(main_run: Dict, sweep: Optional[List[Dict]]) -> str:
    md = []
    md.append("# Titanic RAG — Retrieval Evaluation\n")
    md.append("Auto-generated by `python Evals/run_retrieval_eval.py`. The gold set "
              "(`Evals/gold_set.json`) holds 30 hand-curated queries with labeled "
              "relevant witnesses across both inquiries. A result is counted as "
              "'hitting' a query when the chunk's `witness_name` matches any name "
              "in the query's `relevant_witnesses` list.\n")

    md.append("## Headline numbers\n")
    md.append(f"- **Hit Rate @ 5**: {main_run['hit_rate_at_5']:.1%} "
              f"— {int(main_run['hit_rate_at_5'] * main_run['n_queries'])}/{main_run['n_queries']} "
              f"queries return at least one relevant witness in the top 5")
    md.append(f"- **Recall @ 5**: {main_run['recall_at_5_mean']:.2f} "
              f"— mean fraction of relevant witnesses surfaced in top-5")
    md.append(f"- **Recall @ 10**: {main_run['recall_at_10_mean']:.2f}")
    md.append(f"- **Mean Reciprocal Rank**: {main_run['mrr']:.3f}")
    md.append(f"- **Latency**: p50 {main_run['p50_latency_ms']:.0f} ms, "
              f"p95 {main_run['p95_latency_ms']:.0f} ms (single-thread, against the live Pinecone index)\n")

    md.append(f"Run with `similarity_threshold = {main_run['threshold']}` (the production default).\n")

    if sweep:
        md.append("## Threshold sweep\n")
        md.append("Why is the production default 0.5? The corpus's top-1 similarity "
                  "scores cap around 0.77 — embedding-3-large on short witness Q&A "
                  "chunks doesn't produce high cosine similarities even for great "
                  "matches. A 0.7 threshold (FastAPI/RAG-tutorial default) returns "
                  "zero results for most queries.\n")
        md.append("| threshold | Hit Rate @ 5 | Recall @ 5 | Recall @ 10 | MRR |")
        md.append("|---|---|---|---|---|")
        for run in sweep:
            md.append(f"| {run['threshold']:.2f} | {run['hit_rate_at_5']:.1%} "
                      f"| {run['recall_at_5_mean']:.2f} | {run['recall_at_10_mean']:.2f} "
                      f"| {run['mrr']:.3f} |")
        md.append("")

    md.append("## Methodology\n")
    md.append("- **Gold set**: 30 queries hand-curated from Titanic primary sources, "
              "covering testimony from both the US Senate (1912) and British Wreck "
              "Commissioner's (1912) inquiries. Each query labels every witness "
              "*expected to have testified on the topic* — including both inquiries' "
              "name variants for the same person (e.g. \"Charles Herbert Lightoller\" "
              "and \"Charles Lightoller\" both count as the Lightoller witness).")
    md.append("- **Hit Rate @ 5**: query is a hit if ≥1 relevant witness appears in "
              "the top 5 retrieved chunks. This is the most user-facing metric — it "
              "reflects whether a typical user would see a relevant answer above the fold.")
    md.append("- **Recall @ K**: mean fraction of a query's relevant witnesses that "
              "appear in the top K. Penalizes the system for missing relevant witnesses "
              "when many testified on a topic. Lower than Hit Rate by design.")
    md.append("- **MRR**: 1 / rank of the first relevant witness. Rewards systems "
              "that rank the right answer near the top, not just somewhere in top-K.\n")

    md.append("## Limitations\n")
    md.append("- **Witness-level relevance, not chunk-level.** A query gets credit when "
              "any chunk from a relevant witness appears, even if that specific chunk "
              "isn't the best evidence. Chunk-level labels would be more rigorous but "
              "exponentially more expensive to build.")
    md.append("- **30 queries is small.** Statistical confidence is limited; this is "
              "an indicative measure, not a benchmark. A 200-query gold set would be "
              "the next step for real production use.")
    md.append("- **No human grader for fuzzy cases.** \"Charles Lightoller testified "
              "on lifeboat 6\" is unambiguous historically. \"Did anyone hear the band\" "
              "is hazier — the labeling reflects judgment calls.\n")

    md.append("## Per-query results\n")
    md.append("| Query | Topic | Hit@5 | Recall@5 | Recall@10 | MRR |")
    md.append("|---|---|---|---|---|---|")
    for q in main_run["per_query"]:
        flag = "✅" if q["hit@5"] else "❌"
        md.append(f"| {q['query']} | {q['topic']} | {flag} "
                  f"| {q['recall@5']:.2f} | {q['recall@10']:.2f} | {q['mrr']:.3f} |")

    return "\n".join(md) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true",
                        help="Skip the threshold sweep (run only the default 0.5)")
    args = parser.parse_args()

    gold = load_gold_set()
    print(f"Loaded {len(gold)} gold-set queries from {GOLD_PATH.name}")

    embedding_service = EmbeddingService(model="text-embedding-3-large", dimensions=1024)
    vector_store = PineconeVectorStore()
    engine = SemanticSearchEngine(embedding_service, vector_store)

    print("\nRunning main eval at threshold=0.5 ...")
    main_run = evaluate(engine, gold, threshold=0.5, top_k=10)
    print(f"  Hit Rate @ 5: {main_run['hit_rate_at_5']:.1%}")
    print(f"  Recall @ 5:   {main_run['recall_at_5_mean']:.2f}")
    print(f"  Recall @ 10:  {main_run['recall_at_10_mean']:.2f}")
    print(f"  MRR:          {main_run['mrr']:.3f}")
    print(f"  p50 latency:  {main_run['p50_latency_ms']:.0f} ms")

    sweep = None
    if not args.quick:
        print("\nRunning threshold sweep ...")
        sweep = []
        for thr in [0.3, 0.4, 0.5, 0.6, 0.7]:
            run = evaluate(engine, gold, threshold=thr, top_k=10)
            print(f"  thr={thr:.1f}  Hit@5={run['hit_rate_at_5']:.1%}  "
                  f"R@5={run['recall_at_5_mean']:.2f}  "
                  f"MRR={run['mrr']:.3f}")
            sweep.append(run)

    md = render_md(main_run, sweep)
    OUT_PATH.write_text(md, encoding="utf-8")
    print(f"\nReport written to {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
